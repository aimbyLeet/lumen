#!/usr/bin/env python3
"""Extract `static const GUID NAME = {...};` definitions from nvEncodeAPI.h
into Rust constants (bindgen cannot translate initialized static consts).

Usage: python3 gen_guids.py path/to/nvEncodeAPI.h > ../src/guids.rs
"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
pat = re.compile(
    r"static\s+const\s+GUID\s+(\w+)\s*=\s*\{\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*,"
    r"\s*(0x[0-9a-fA-F]+)\s*,\s*\{([^}]*)\}\s*\}\s*;",
    re.S,
)
print("// @generated by scripts/gen_guids.py from nv-codec-headers. Do not edit.")
print("use crate::GUID;\n")
count = 0
for name, d1, d2, d3, d4 in pat.findall(src):
    bytes_ = [b.strip() for b in d4.split(",") if b.strip()]
    assert len(bytes_) == 8, name
    print(
        f"pub const {name}: GUID = GUID {{ Data1: {d1}, Data2: {d2}, Data3: {d3}, "
        f"Data4: [{', '.join(bytes_)}] }};"
    )
    count += 1
assert count > 0, "no GUIDs found"
